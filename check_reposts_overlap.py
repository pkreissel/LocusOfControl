import json
import urllib.request
import os
from dotenv import load_dotenv

def main():
    load_dotenv('bunny_feed/.env')
    load_dotenv('.env')
    ge_api_key = os.environ.get('GREEN_EARTH_API_KEY')
    user_did = "did:plc:xo2uz55ugf2yguhjryahasuf"

    with open('reposts_analysis.json', 'r') as f:
        reposts = json.load(f)
    
    repost_uris = {p['uri'] for p in reposts}
    print(f"Total reposts in your history (last 7 days): {len(repost_uris)}")

    req = urllib.request.Request(
        'https://api.greenearth.social/candidates/generate',
        data=json.dumps({
            "generators": [
                { "name": "followed_users", "weight": 1.0 },
                { "name": "network_likes", "weight": 1.0 },
                { "name": "two_tower", "weight": 1.0 }
            ],
            "infill": "popularity",
            "user_did": user_did,
            "num_candidates": 1000
        }).encode('utf-8'),
        headers={'Content-Type': 'application/json', 'X-API-Key': ge_api_key}
    )
    
    with urllib.request.urlopen(req) as response:
        cand_data = json.loads(response.read().decode('utf-8'))
        
    candidates = cand_data.get('candidates', [])
    cand_uris = {c['at_uri'] for c in candidates}
    
    overlap = repost_uris.intersection(cand_uris)
    print(f"Candidates generated by GE: {len(cand_uris)}")
    print(f"Number of your recent reposts naturally included in these candidates: {len(overlap)}")
    
if __name__ == '__main__':
    main()
